import numpy as np
import qiskit
import qiskit.quantum_info as qi

def Z_gates_to_choi(z1,z2):

    circ = qiskit.QuantumCircuit(2)
    circ.rz(2*np.pi*z1,0)
    circ.rz(2*np.pi*z2,1)

    choi = qi.Choi(circ)
    return choi

def optimize_Z_rotations(choi,choi_target):

    z1s = np.linspace(0,1,100)
    z2s = np.linspace(0,1,100)
    fidels = np.zeros([100,100])

    for i,z1 in enumerate(z1s):
        for j,z2 in enumerate(z2s):
            z_choi = Z_gates_to_choi(z1,z2)
            full_choi = choi.compose(z_choi)
            fidels[i][j] = qi.process_fidelity(full_choi,target=choi_target,require_cp=False,require_tp=False)

    return fidels
